import { it, expect, vi } from "vitest";
import nativeFs from "node:fs";
import fs from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import { randomUUID } from "node:crypto";
import { FileRepository } from "../repository/file-repository";
import { trackingSlots } from "../tracking-slots";
import { RoutingService, RoutingStore } from "./service";
import { verificationFromHousehold } from "./verification-bridge";
import { syntheticBooking, syntheticInput } from "./fixtures";
import { bookingToPickup } from "./contracts";
import { syntheticPreparation } from "./fixtures";
import { confirmedSlotWindow } from "./windows";

it("persists booking → independent evidence → dispatch → preparation → validated routing and lifecycle exclusions", async () => {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), "recircuit-scheduling-"));
  const repo = new FileRepository(path.join(root, "portal"));
  const template = syntheticBooking();
  const { id: _id, status: _status, events: _events, bookingReference: _ref, createdAt: _created, updatedAt: _updated, ...data } = template;
  void [_id, _status, _events, _ref, _created, _updated];
  const first = await repo.createBooking(data), booking = first.booking;
  expect(first.isDuplicate).toBe(false);
  expect((await repo.createBooking(data)).booking.id).toBe(booking.id);
  const input = syntheticInput(1), records: unknown[] = [];
  const source = { list: (tenant: typeof booking.recyclerId) => repo.listBookings(tenant), verification: async (tenant: typeof booking.recyclerId, b: typeof booking) => verificationFromHousehold(tenant, b, records) };
  const provider = { configurationId: "scheduling-test-fixture", matrix: async (request: { tenant: typeof booking.recyclerId; nodes: typeof input.matrix.nodes }) => ({ ...input.matrix, tenant: request.tenant, nodes: request.nodes }) };
  const store = new RoutingStore(path.join(root, "routing")), service = new RoutingService(source, store, provider);
  const preview = (date = "2026-10-24") => service.preview("deccan", date);
  expect((await preview()).conversions).toEqual([]);
  await repo.updateBookingStatus("deccan", booking.bookingReference, "CONFIRMED", "Dispatcher confirmed receipt");
  records.push({ request: { id: "local-test-approved-request", state: "APPROVED" }, plan: { legs: [{ id: "leg", recyclerId: "deccan", bookingReference: booking.bookingReference, state: "REQUEST_CONFIRMED" }] }, household: { customer: data, verifications: { leg: { verified: true, independent: true, isUncertain: false, bookingReference: booking.bookingReference, observedItems: booking.items, observedFeeText: "INR 180", checkedAt: new Date().toISOString() } } } });
  expect((await preview()).conversions).toEqual([]);
  const schedule = (date: string) => repo.updateBookingStatus("deccan", booking.bookingReference, "SCHEDULED", "Simulated dispatcher assignment", { slot: date + " (10:00-12:00 IST)", isSimulated: true });
  const scheduled = (await schedule("2026-10-24"))!;
  expect(trackingSlots(scheduled).requestedSlot).toBe(data.preferredSlot);
  expect((await preview()).conversions[0]).toMatchObject({ eligible: false, reasons: expect.arrayContaining(["COORDINATE_REVIEW_REQUIRED"]) });
  expect((await service.preview("paperplus", "2026-10-24")).conversions).toEqual([]);
  expect(await repo.getBookingByReference("paperplus", booking.bookingReference)).toBeNull();
  await service.vehicles("deccan", input.vehicles);
  await service.review("deccan", { bookingId: booking.id, coordinate: input.pickups[0]!.coordinate, serviceSeconds: 60, assumptionVersion: "simulated-test" }, "local-test-dispatcher");
  expect((await preview()).conversions[0]?.eligible).toBe(true);
  const proposal = await service.generate("deccan", "2026-10-24", randomUUID());
  expect(proposal.independentValidation).toEqual({ valid: true, errors: [] });
  expect(proposal.optimization.solution.served).toBe(1);
  const original = await fs.readFile(path.join(root, "routing/deccan/proposals/00000001.json"), "utf8");
  await schedule("2026-10-25");
  expect((await preview()).conversions).toEqual([]);
  expect((await preview("2026-10-25")).conversions[0]?.eligible).toBe(true);
  expect((await service.read("deccan", proposal.id)).current).toBe(false);
  await repo.updateBookingStatus("deccan", booking.bookingReference, "CANCELLED", "Cancelled");
  expect((await preview("2026-10-25")).conversions).toEqual([]);
  await expect(schedule("2026-10-24")).rejects.toThrow("NO_LONGER_ACTIVE");
  const second = (await repo.createBooking({ ...data, clientRequestId: data.clientRequestId + "-second" })).booking;
  await repo.updateBookingStatus("deccan", second.bookingReference, "SCHEDULED", "Scheduled", { slot: "2026-10-24 (10:00-12:00 IST)" });
  records.push({ request: { id: "local-second-approved-request", state: "APPROVED" }, plan: { legs: [{ id: "second-leg", recyclerId: "deccan", bookingReference: second.bookingReference, state: "REQUEST_CONFIRMED" }] }, household: { customer: second, verifications: { "second-leg": { verified: true, independent: true, isUncertain: false, bookingReference: second.bookingReference, observedItems: second.items, observedFeeText: "INR 180", checkedAt: new Date().toISOString() } } } });
  await service.review("deccan", { bookingId: second.id, coordinate: input.pickups[0]!.coordinate, serviceSeconds: 60, assumptionVersion: "simulated-second-test" }, "local-test-dispatcher");
  expect((await preview()).conversions).toEqual([expect.objectContaining({ eligible: true })]);
  await repo.updateBookingStatus("deccan", second.bookingReference, "PICKED_UP", "Collected");
  expect((await preview()).conversions).toEqual([]);
  const reloadedRepo = new FileRepository(path.join(root, "portal"));
  expect((await reloadedRepo.getBookingByReference("deccan", booking.bookingReference))?.status).toBe("CANCELLED");
  expect((await reloadedRepo.getBookingByReference("deccan", booking.bookingReference))?.chargedFeeInr).toBe(180);
  expect(await fs.readFile(path.join(root, "routing/deccan/proposals/00000001.json"), "utf8")).toBe(original);
  await expect(service.read("paperplus", proposal.id)).rejects.toThrow("NOT_FOUND");
});

it("fails closed for unscheduled states, mismatched dates and forged preparation windows", () => {
  const b = syntheticBooking(), preparation = syntheticPreparation(b);
  for (const status of ["RECEIVED", "CONFIRMED", "CANCELLED", "PICKED_UP", "WEIGHED"] as const) expect(bookingToPickup({ ...b, status }, preparation).eligible).toBe(false);
  expect(confirmedSlotWindow("2026-10-25 (10:00-12:00 IST)", "2026-10-24")).toBeNull();
  expect(confirmedSlotWindow("2026-10-23 (23:00-02:00 IST)", "2026-10-24")).toBeNull();
  expect(bookingToPickup(b, { ...preparation, confirmedWindow: { start: 0, end: 86400 } }).eligible).toBe(false);
  expect(bookingToPickup({ ...b, events: [] }, preparation).eligible).toBe(false);
});

it("serializes separate repositories, rejects stale edits and never publishes a partial status/history write", async () => {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), "recircuit-dispatch-write-"));
  const a = new FileRepository(root), b = new FileRepository(root), template = syntheticBooking();
  const { id: _id, status: _status, events: _events, bookingReference: _ref, createdAt: _created, updatedAt: _updated, ...data } = template;
  void [_id, _status, _events, _ref, _created, _updated];
  const [first] = await Promise.all([a.createBooking(data), b.createBooking({ ...data, clientRequestId: data.clientRequestId + "-other" })]);
  expect(await a.listBookings("deccan")).toHaveLength(2);
  const options = { expectedUpdatedAt: first.booking.updatedAt, slot: "2026-10-24 (10:00-12:00 IST)" };
  const results = await Promise.allSettled([a.updateBookingStatus("deccan", first.booking.bookingReference, "SCHEDULED", "First edit", options), b.updateBookingStatus("deccan", first.booking.bookingReference, "SCHEDULED", "Concurrent edit", { ...options, slot: "2026-10-25 (10:00-12:00 IST)" })]);
  expect(results.filter(r => r.status === "fulfilled")).toHaveLength(1);
  expect(results.filter(r => r.status === "rejected")).toHaveLength(1);
  const before = await fs.readFile(path.join(root, "deccan.json"), "utf8");
  const rename = vi.spyOn(nativeFs, "renameSync").mockImplementation(() => { throw Error("TEST_DISK_WRITE_FAILURE"); });
  try { await expect(a.updateBookingStatus("deccan", first.booking.bookingReference, "CANCELLED", "Must not partially persist")).rejects.toThrow("TEST_DISK_WRITE_FAILURE"); } finally { rename.mockRestore(); }
  expect(await fs.readFile(path.join(root, "deccan.json"), "utf8")).toBe(before);
});
